def write(p,text):
    prop=deepcopy(p.runs[0]._r.rPr) if p.runs else None
    for r in list(p.runs): p._p.remove(r._r)
    r=p.add_run(text)
    if prop is not None:r._r.insert(0,prop)

def replace_many(p,texts):
    template=deepcopy(p._p)
    write(p,texts[0]); last=p._p
    for text in texts[1:]:
        element=deepcopy(template);last.addnext(element)
        new=Paragraph(element,p._parent);write(new,text);last=element

